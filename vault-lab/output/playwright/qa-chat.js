async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  let releaseResponse;
  let attempts = 0;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.route('**/api/status', route => route.fulfill({ json: { configured: true, mode: 'practice', bountyEnabled: false } }));
    await page.route('**/api/attempt', async route => {
      const input = route.request().postDataJSON();
      if (input.prompt === 'QA: request rejected before inference') {
        await route.fulfill({ status: 409, json: { error: { code: 'ATTEMPT_BUSY', message: 'QA test: another attempt is still running.' } } });
        return;
      }
      attempts += 1;
      if (attempts === 1) await new Promise(resolve => { releaseResponse = resolve; });
      const decision = attempts === 1 ? 'locked' : 'released';
      const receipt = { id: `qa-${attempts}`, sessionId: 'qa-session', status: 'complete', decision, modelRequested: input.modelId, modelReturned: input.modelId, provider: 'QA fixture — no inference', promptVersion: 'QA only', createdAt: new Date().toISOString(), usage: { prompt_tokens: 123, completion_tokens: 44, total_tokens: 167, cost: 0 }, inputMessages: [{ role: 'user', content: input.prompt }] };
      await route.fulfill({ json: { sessionId: 'qa-session', attemptId: receipt.id, modelId: input.modelId, decision, response: `Controlled QA response: ${decision}. This is not real inference.`, receipt } });
    });
    await page.reload();
    await page.locator('#model-button:not([disabled])').waitFor();
    await page.getByRole('textbox', { name: 'Your message' }).fill('Interface test message, without inference.');
    assert(await page.locator('#guardian-stage').getAttribute('data-state') === 'watching', 'Mascot must attend to the draft');
    const sent = page.waitForRequest('**/api/attempt');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await sent;
    assert(await page.locator('#guardian-stage').getAttribute('data-state') === 'thinking', 'Pending request must own the thinking pose');
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    releaseResponse();
    await page.locator('.message.assistant').waitFor({ state: 'attached' });
    assert(await page.locator('#chat-main').evaluate(node => node.inert), 'Mobile chat must be inert behind settings');
    assert(await page.locator('#close-settings').evaluate(node => node === document.activeElement), 'Response must not steal settings focus');
    await page.getByRole('button', { name: 'Close settings' }).click();
    assert(await page.locator('#attempt-count').innerText() === '1', 'First receipt is missing');
    assert(await page.locator('#vault-state').innerText() === 'Vault locked', 'Locked state missing');
    assert(await page.locator('#guardian-poke').isVisible(), 'Mascot must remain visible after reply');
    assert(await page.locator('#guardian-line').innerText() === 'Controlled QA response: locked. This is not real inference.', 'Bubble must contain the actual response');
    await page.locator('#guardian-poke').click();
    assert(await page.locator('#guardian-line').innerText() === 'Controlled QA response: locked. This is not real inference.', 'Poking must not replace a model reply');
    await page.locator('#transcript-button').click();
    assert(await page.locator('#chat-thread .message').count() === 2, 'Transcript must contain each message exactly once');
    assert(await page.locator('#chat-thread').getAttribute('aria-live') === 'off', 'History must not repeat the live response');
    await page.locator('#chat-thread .receipt-button').click();
    await page.getByRole('heading', { name: 'Attempt receipt' }).waitFor();
    await page.getByRole('button', { name: 'Close details' }).click();
    assert(await page.locator('#transcript-dialog').isVisible(), 'Nested receipt must preserve transcript');
    await page.getByRole('button', { name: 'Close transcript' }).click();
    await page.screenshot({ animations: 'disabled', path: 'output/playwright/vault-mascot-qa-response.png' });
    await page.getByRole('button', { name: 'Make a meme' }).click();
    await page.locator('.share-preview canvas').waitFor();
    const imageDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download PNG' }).click();
    await (await imageDownload).saveAs('output/playwright/vault-english-qa-meme.png');
    await page.getByRole('button', { name: 'Close image' }).click();
    await page.getByRole('textbox', { name: 'Your message' }).fill('Second QA message.');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await page.locator('#guardian-stage[data-state="released"]').waitFor();
    assert(await page.locator('#prompt').isDisabled(), 'Released session must stop accepting messages');
    assert(await page.locator('#attempt-count').innerText() === '2', 'Second receipt is missing');
    await page.getByRole('button', { name: 'View receipt', exact: true }).last().click();
    await page.getByRole('heading', { name: 'Attempt receipt' }).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download receipt JSON' }).click();
    const download = await downloadPromise;
    await download.saveAs('output/playwright/qa-receipt.json');
    await page.getByRole('button', { name: 'Close details' }).click();
    await page.locator('#reset-button').click();
    await page.getByRole('button', { name: 'Keep this chat' }).click();
    assert(await page.locator('#prompt').isDisabled(), 'Cancel must preserve released session');
    await page.locator('#reset-button').click();
    await page.getByRole('button', { name: 'Start over', exact: true }).click();
    assert(await page.locator('#chat-main').getAttribute('data-empty') === 'true', 'New conversation must restore empty chat');
    assert(await page.locator('#guardian-source').innerText() === 'Character intro', 'Reset must restore authored greeting');
    assert(await page.locator('#guardian-bubble-actions').isHidden(), 'Reset must remove old response actions');
    assert(await page.locator('#transcript-count').innerText() === '0', 'Reset must clear transcript count');
    assert(await page.locator('#attempt-count').innerText() === '2', 'Reset must preserve exportable receipts');
    await page.getByRole('textbox', { name: 'Your message' }).fill('QA: request rejected before inference');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    await page.locator('#guardian-stage[data-state="error"]').waitFor();
    assert((await page.locator('#notice').innerText()).includes('The attempt was not sent to the model.'), 'Busy failure must identify no inference');
    assert((await page.locator('#guardian-source').innerText()).includes('not a model reply'), 'Connection error must not impersonate the guardian');
    assert(await page.locator('#vault-state').innerText() === 'Vault locked', 'Pre-inference refusal must not claim unknown result');
    assert(!(await page.locator('#prompt').isDisabled()), 'Pre-inference busy must not lock this session');
    assert(await page.locator('#attempt-count').innerText() === '2', 'Rejected request must not invent a receipt');
    await page.locator('#prompt').fill('A draft that must be preserved.');
    await page.keyboard.press('Control+k');
    await page.getByRole('searchbox', { name: 'Search models or providers' }).fill('gemini');
    await page.getByRole('button', { name: 'Choose Google: Gemini 2.5 Flash', exact: true }).click();
    await page.getByRole('button', { name: 'Keep this chat' }).click();
    assert(await page.locator('#prompt').inputValue() === 'A draft that must be preserved.', 'Cancelled switch must preserve draft');
    await page.keyboard.press('Control+k');
    await page.getByRole('searchbox', { name: 'Search models or providers' }).fill('gemini');
    await page.getByRole('button', { name: 'Choose Google: Gemini 2.5 Flash', exact: true }).click();
    await page.getByRole('button', { name: 'Start over', exact: true }).click();
    assert((await page.locator('#model-label').innerText()).includes('Gemini'), 'Model switch must apply after confirmation');
    assert(errors.length === 0, `Browser errors: ${errors.join(', ')}`);
    console.log('PASS: mascot draft/thinking/locked/released/error/reset, persistent real reply, poke without fake dialogue, transcript/nested receipt, meme/export, model switch, mobile panel inert and no focus theft. Mock responses only; zero inference calls.');
  } finally {
    await page.unrouteAll({ behavior: 'ignoreErrors' });
    await page.reload();
  }
}
