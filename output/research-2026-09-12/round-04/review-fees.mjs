// Offline independent reconciliation against retained Blockscout responses.
import fs from 'node:fs';
const dir = new URL('../round-03/fees/', import.meta.url);
const read = name => JSON.parse(fs.readFileSync(new URL(name, dir), 'utf8'));
const sales = read('sales-final.json');
const txs = read('sale-transactions.json');
const ledger = read('fee-ledger.json');
const legacy = read('sale-internal-transfers.json');
const legacyTest = read('internal-legacy-test.json');
const pages = read('sale-internal-v2-pages.json');
const transferPages = JSON.parse(fs.readFileSync(new URL('sale-token-transfer-pages.json',import.meta.url),'utf8').replace(/^\uFEFF/,''));
const receiver = '0x79b069112df103f28be2012a52ecef0f4a5106f2';
const feeRecipient = '0xb8159ba378904f803639d274cec79f788931c9c8';
const cat = '0xd6fde6a3fc6ab2d83b2be58383944ca1bade1e18';
const openai = '0xfe09fb328be1c286b4f597ed34764b7472ae72c5';
const lower = x => x.toLowerCase();
const raw = n => { const [a,b=''] = String(n).split('.'); return BigInt(a) * 10n**18n + BigInt(b.padEnd(18,'0')); };
const units = n => `${n/10n**18n}.${(n%10n**18n).toString().padStart(18,'0')}`;
const sum = values => values.reduce((a,b)=>a+b,0n);
const errors = [];
const check = (condition, message) => { if (!condition) errors.push(message); };
const results = [];
for (const s of sales.rows) {
  const t = txs.find(x=>x.data.hash===s.tx);
  check(!!t, `Missing transaction ${s.tx}`);
  check(t.data.status==='ok', `Failed transaction ${s.tx}`);
  check(lower(t.data.from.hash)===receiver, `Wrong sender ${s.tx}`);
  check(t.data.fee.type==='actual', `Fee not actual ${s.tx}`);
  check(BigInt(t.data.fee.value)===raw(s.gasEth), `Gas total mismatch ${s.tx}`);
  check(BigInt(t.data.gas_used)*BigInt(t.data.gas_price)===raw(s.gasEth), `Gas arithmetic mismatch ${s.tx}`);
  const extra=transferPages.filter(x=>x.tx===s.tx).sort((a,b)=>a.page-b.page);
  const transfers=extra.length ? extra.flatMap(x=>x.data.items) : t.data.token_transfers;
  const tokensComplete=extra.length ? extra.at(-1).data.next_page_params===null : t.data.token_transfers_overflow===false;
  check(tokensComplete, `Incomplete token response ${s.tx}`);
  const matchingTransfers=transfers.filter(x=>lower(x.from.hash)===receiver && lower(x.token.address_hash)===lower(s.tokenAddress) && x.total.value===s.tokenAmountRaw);
  check(matchingTransfers.length===1, `Token debit mismatch ${s.tx}`);
  check(transfers.filter(x=>lower(x.from.hash)===receiver).length===1, `Additional token debit from receiver ${s.tx}`);
  check(transfers.filter(x=>lower(x.to.hash)===receiver).length===0, `Token credit to receiver ${s.tx}`);
  check(raw(s.tokenAmount)===BigInt(s.tokenAmountRaw), `Human quantity mismatch ${s.tx}`);
  const claim = ledger.ledger.find(x=>x.event==='Release' && x.tx===s.claim && lower(x.recipient)===receiver);
  check(!!claim, `No receiver Release ${s.tx}`);
  const claimAmount = lower(s.tokenAddress)===cat ? claim.token0Raw : lower(s.tokenAddress)===openai ? claim.token1Raw : undefined;
  check(claimAmount===s.tokenAmountRaw, `Claim leg mismatch ${s.tx}`);
  const secondsAfter=(new Date(t.data.timestamp)-new Date(claim.timestamp))/1000;
  check(secondsAfter>=0 && secondsAfter<=30, `Outside 30 seconds ${s.tx}`);
  const p=pages.filter(x=>x.tx===s.tx).sort((a,b)=>a.page-b.page);
  let traces, source, complete;
  if(p.length) {
    traces=p.flatMap(x=>x.data.items).map(x=>({index:String(x.index),from:lower(x.from.hash),to:lower(x.to?.hash??''),type:x.type,valueRaw:x.value,success:x.success}));
    complete=p.at(-1).data.next_page_params===null && p.every((x,i)=>x.page===i+1);
    source='Blockscout v2 paginated';
  } else {
    const original=legacy.find(x=>x.tx===s.tx && x.data?.status==='1')?.data ?? (legacyTest.data.result[0].transactionHash===s.tx ? legacyTest.data : null);
    check(!!original, `Missing internal raw ${s.tx}`);
    traces=original.result.map(x=>({index:String(x.index),from:lower(x.from),to:lower(x.to),type:x.type,valueRaw:x.value,success:x.isError==='0'}));
    complete=original.status==='1';
    source='Blockscout legacy internal list';
  }
  check(complete, `Incomplete internal pages ${s.tx}`);
  check(new Set(traces.map(x=>x.index)).size===traces.length, `Duplicate raw trace ${s.tx}`);
  const payments=traces.filter(x=>x.success && x.type==='call' && [receiver,feeRecipient].includes(x.to) && BigInt(x.valueRaw)>0n);
  check(payments.length===2, `Unexpected payment count ${s.tx}`);
  const received=sum(payments.filter(x=>x.to===receiver).map(x=>BigInt(x.valueRaw)));
  const routerFee=sum(payments.filter(x=>x.to===feeRecipient).map(x=>BigInt(x.valueRaw)));
  const gross=received+routerFee;
  check(received===raw(s.ethReceived), `Received mismatch ${s.tx}`);
  check(routerFee===raw(s.routerFeeEth), `Router fee mismatch ${s.tx}`);
  check(routerFee===gross/100n, `Router fee not floor 1% gross ${s.tx}`);
  results.push({tx:s.tx,claim:s.claim,secondsAfter,token:s.token,tokenRaw:s.tokenAmountRaw,source,complete,tokensComplete,tokenTransfersCount:transfers.length,receivedWei:String(received),routerFeeWei:String(routerFee),grossWei:String(gross),gasWei:t.data.fee.value,routerFeeIsFloorOnePercent:routerFee===gross/100n});
}
const received=sum(results.map(x=>BigInt(x.receivedWei)));
const routerFee=sum(results.map(x=>BigInt(x.routerFeeWei)));
const gas=sum(results.map(x=>BigInt(x.gasWei)));
check(sales.rows.length===19,'Expected 19 sales');
check(new Set(results.map(x=>x.claim)).size===15,'Expected 15 distinct claims');
check(new Set(results.map(x=>x.tx)).size===19,'Duplicate sale hash');
check(raw(sales.summary.ethReceived)===received,'Summary receiver total');
check(raw(sales.summary.routerFeeEth)===routerFee,'Summary router fee total');
check(raw(sales.summary.salesGasEth)===gas,'Summary gas total');
check(raw(sales.summary.ethReceivedMinusSalesGas)===received-gas,'Summary net of sales gas only');
const tokens=['CATGPT','OPENAIx1L'].map(token=>{
  const rows=results.filter(x=>x.token===token);
  const amount=sum(rows.map(x=>BigInt(x.tokenRaw)));
  const eth=sum(rows.map(x=>BigInt(x.receivedWei)));
  const prior=sales.summary.tokens.find(x=>x.token===token);
  check(raw(prior.tokenAmount)===amount && raw(prior.ethReceived)===eth,`Summary ${token}`);
  return {token,count:rows.length,amount:units(amount),receiverEth:units(eth)};
});
const out={reviewedAt:new Date().toISOString(),method:'Offline BigInt re-sum from retained transaction and internal-trace raw; no RPC or wallet call',errors,sales:results.length,distinctClaims:new Set(results.map(x=>x.claim)).size,completeTraceSales:results.filter(x=>x.complete).length,receiver,feeRecipient,tokens,totals:{grossBeforeObservedRouterFeeEth:units(received+routerFee),routerFeeEth:units(routerFee),receiverEth:units(received),salesGasEth:units(gas),receiverMinusOnlySalesGasEth:units(received-gas)},rows:results};
fs.writeFileSync(new URL('fees-review-calculations.json',import.meta.url),JSON.stringify(out,null,2));
console.log(JSON.stringify({...out,rows:undefined},null,2));
if(errors.length)process.exitCode=1;
